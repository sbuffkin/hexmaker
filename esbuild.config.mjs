import esbuild from "esbuild";
import process from "process";
import { createRequire } from "module";
import { sliceFlags, sliceModules, stripSliceMarkers } from "./dev/release/slices.mjs";

const require = createRequire(import.meta.url);
const manifest = require("./manifest.json");
const fs = require("fs");

const args = process.argv.slice(2);
const production = args.includes("production");

// Release slices (release-slices.json): `npm run build` is the release
// build (the slices marked released); `--full` (build:full, and dev) builds
// every slice. HEXMAKER_SLICES_OFF=space,worldmaps turns slices off on top
// (npm run check:release). HEXMAKER_OUTFILE writes somewhere else.
const { flags, off, channel } = sliceFlags({
	full: args.includes("--full") || !production,
	off: process.env.HEXMAKER_SLICES_OFF,
});

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
build channel: ${channel}
*/
`;

const prod = production;
const outFile = process.env.HEXMAKER_OUTFILE || "main.js";

/** Markdown imported as text, with the blocks of slices built off removed (help.md). */
const sliceMarkdown = {
	name: "slice-markdown",
	setup(build) {
		build.onLoad({ filter: /\.md$/ }, async (a) => {
			const text = await fs.promises.readFile(a.path, "utf8");
			return { contents: stripSliceMarkers(text, off), loader: "text" };
		});
	},
};

/**
 * A slice built off: its modules' two entry files (src/modules/<id>/index.ts
 * and runtime.ts) load as stubs that export the same names as undefined.
 * src/modules/index.ts and runtime.ts only push them behind the slice's
 * flag, and nothing else in the core imports a module (the boundary
 * ratchet), so none of the module's code reaches the bundle. (esbuild
 * keeps `if (false)` branches and their imports unless minifying.)
 */
const offModules = new Set(sliceModules(off));
const sliceStubs = {
	name: "slice-stubs",
	setup(build) {
		build.onLoad({ filter: /[\\/]src[\\/]modules[\\/][^\\/]+[\\/](index|runtime)\.ts$/ }, async (a) => {
			const id = a.path.split(/[\\/]/).slice(-2, -1)[0];
			if (!offModules.has(id)) return undefined;
			const real = await fs.promises.readFile(a.path, "utf8");
			const names = [...real.matchAll(/^export (?:const|function|class) (\w+)/gm)].map((m) => m[1]);
			return { contents: `// slice off: module ${id} not built\n${names.map((n) => `export const ${n} = undefined;`).join("\n")}\n`, loader: "ts" };
		});
	},
};

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ["main.ts"],
	bundle: true,
	external: ["obsidian"],
	format: "cjs",
	target: "es2018",
	logLevel: process.env.HEXMAKER_OUTFILE ? "warning" : "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	outfile: outFile,
	loader: { ".md": "text", ".png": "dataurl", ".svg": "dataurl" },
	plugins: [sliceMarkdown, sliceStubs],
	// The version stamped on files the plugin writes (src/compat.ts). Taken from
	// manifest.json at build time: Obsidian keeps the manifest it read at startup,
	// so plugin.manifest.version can be stale after an update without a restart.
	define: {
		__HEXMAKER_VERSION__: JSON.stringify(manifest.version),
		...Object.fromEntries(Object.entries(flags).map(([k, v]) => [k, JSON.stringify(v)])),
	},
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
