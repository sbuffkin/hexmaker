/**
 * "Edit region…" (#49): what the modal offers per work mode, the facts it
 * shows, and the region notes it keeps in the map note's `## Notes`.
 */
import { describe, it } from "node:test";
import expect from "expect";
import { BIOME_LOCKED_HINT, editRegionPlan, terrainCountsText } from "../src/overworld/overworldInput";
import { NOTES_HEADING, readNotesSection, writeNotesSection } from "../src/maps/mapNoteNotes";
import { buildMapNote, parseMapNote, terrainCounts, updateMapNote, type MapNoteData } from "../src/maps/mapNote";

const m = (mode: string | undefined) => ({ workMode: mode });

describe("Edit region: sections per work mode", () => {
	it("God shows the biome picker with Reroll and Settings…", () => {
		expect(editRegionPlan(m("god"))).toEqual({ biome: "pick", reroll: true, settings: true });
	});

	it("Build and Play show the biome read-only with one line, no buttons", () => {
		for (const mode of ["build", "play", undefined]) {
			expect(editRegionPlan(m(mode))).toEqual({ biome: "show", reroll: false, settings: false, hint: BIOME_LOCKED_HINT });
		}
		expect(BIOME_LOCKED_HINT).toBe("Switch to God to change it.");
	});
});

describe("Edit region: facts", () => {
	it("terrain counts cover the whole grid, base terrain filling unlisted hexes", () => {
		const hexes = new Map([["0_0", { terrain: "forest" }], ["1_0", { terrain: "forest" }], ["0_1", { terrain: "hills" }]]);
		const { counts, blank } = terrainCounts(hexes, { gridSize: { cols: 2, rows: 2 }, gridOffset: { x: 0, y: 0 }, baseTerrain: "plains" });
		expect([...counts]).toEqual([["forest", 2], ["hills", 1], ["plains", 1]]);
		expect(blank).toBe(0);
		expect(terrainCounts(hexes, { gridSize: { cols: 2, rows: 2 } }).blank).toBe(1);
	});

	it("the counts read as one short line, most first", () => {
		expect(terrainCountsText(new Map([["hills", 3], ["forest", 30], ["lake", 3]]))).toBe("forest 30, hills 3, lake 3");
		expect(terrainCountsText(new Map([["a", 5], ["b", 4], ["c", 3], ["d", 2], ["e", 1]]), 2)).toBe("a 5, b 4, c 3, d 2 and 2 more");
		expect(terrainCountsText(new Map(), 0)).toBe("none yet");
		expect(terrainCountsText(new Map([["forest", 1]]), 4)).toBe("forest 1, blank 4");
	});
});

const NOTE = [
	"---",
	"hexmaker-map: 5",
	"---",
	"# Saltmere",
	"",
	"## Summary",
	"",
	"*Generated by Hexmaker from the tables below and the map's palette. Edits here are replaced.*",
	"",
	"## Hexes",
	"",
	"| Hex | Terrain |",
	"| --- | --- |",
	"| 0, 0 | forest |",
	"",
].join("\n");

describe("Edit region: notes in the map note", () => {
	it("round-trips through a `## Notes` section placed above the Summary", () => {
		const text = "Salt flats and a drowned abbey.\n\nThe ferry runs at dawn.";
		const out = writeNotesSection(NOTE, text);
		expect(readNotesSection(out)).toBe(text);
		expect(out.indexOf(NOTES_HEADING)).toBeLessThan(out.indexOf("## Summary"));
		expect(out).toContain("# Saltmere\n\n## Notes\n\nSalt flats and a drowned abbey.\n\nThe ferry runs at dawn.\n\n## Summary");
		// Writing the same text again changes nothing.
		expect(writeNotesSection(out, text)).toBe(out);
	});

	it("replaces only its own lines, keeping the rest of the note as it was", () => {
		const once = writeNotesSection(NOTE, "first");
		const twice = writeNotesSection(once, "second\nline");
		expect(readNotesSection(twice)).toBe("second\nline");
		expect(twice.replace(/## Notes\n\nsecond\nline\n\n/, "")).toBe(NOTE);
		expect(twice.split("## Notes").length).toBe(2);
	});

	it("keeps a section the user wrote by hand (its heading and place), and ### subheadings inside it", () => {
		const hand = NOTE.replace("## Hexes", "## Notes\nold text\n### Factions\nthe reeve\n\n## Hexes");
		expect(readNotesSection(hand)).toBe("old text\n### Factions\nthe reeve");
		const out = writeNotesSection(hand, "new text\n### Factions\nthe reeve");
		expect(out.indexOf("## Notes")).toBeGreaterThan(out.indexOf("## Summary"));
		expect(readNotesSection(out)).toBe("new text\n### Factions\nthe reeve");
	});

	it("escapes a typed # or ## line so it can't end the section, and reads it back as typed", () => {
		const out = writeNotesSection(NOTE, "intro\n## not a heading\n# nor this");
		expect(out).toContain("\\## not a heading");
		expect(readNotesSection(out)).toBe("intro\n## not a heading\n# nor this");
	});

	it("blank notes add nothing; clearing keeps the heading empty", () => {
		expect(writeNotesSection(NOTE, "  \n")).toBe(NOTE);
		const cleared = writeNotesSection(writeNotesSection(NOTE, "x"), "");
		expect(readNotesSection(cleared)).toBe("");
		expect(cleared).toContain("## Notes\n\n## Summary");
	});

	it("keeps CRLF notes CRLF and ignores frontmatter", () => {
		const crlf = NOTE.replace(/\n/g, "\r\n");
		const out = writeNotesSection(crlf, "a\nb");
		expect(out.includes("\n") && !/[^\r]\n/.test(out)).toBe(true);
		expect(readNotesSection(out)).toBe("a\nb");
		expect(readNotesSection("---\nnotes: x\n---\n# T\n")).toBe("");
	});

	it("survives the map note writer and isn't read as data", () => {
		const data: MapNoteData = {
			settings: { gridSize: { cols: 2, rows: 1 }, gridOffset: { x: 0, y: 0 } } as MapNoteData["settings"],
			hexes: new Map([["0_0", { terrain: "forest" }]]),
			paths: [],
		};
		const note = writeNotesSection(buildMapNote("saltmere", data), "Salt flats.");
		const next: MapNoteData = { ...data, hexes: new Map([["0_0", { terrain: "hills" }], ["1_0", { terrain: "lake" }]]) };
		const rewritten = updateMapNote(note, "saltmere", next);
		expect(readNotesSection(rewritten)).toBe("Salt flats.");
		expect([...parseMapNote(rewritten)!.hexes]).toEqual([...next.hexes]);
	});
});
